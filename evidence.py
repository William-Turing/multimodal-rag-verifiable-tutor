"""Pure provenance validation and explicit source mapping (no Streamlit dependency)."""
from __future__ import annotations

from dataclasses import dataclass, asdict
import json
import math
from pathlib import Path
from typing import Any, Mapping


@dataclass(frozen=True)
class Source:
    source_id: str
    kind: str  # 'document' or 'video'
    path: Path
    display_name: str
    aliases: tuple[str, ...]


@dataclass(frozen=True)
class Evidence:
    evidence_id: str
    kind: str  # text, image, video
    text: str
    metadata: dict[str, Any]
    page: int | None
    seconds: float | None
    source_id: str | None
    source_name: str
    status: str
    reason: str

    def serializable(self) -> dict[str, Any]:
        return asdict(self)


def parse_page(value: Any) -> int | None:
    if isinstance(value, bool):
        return None
    if isinstance(value, int) and value > 0:
        return value
    if isinstance(value, str) and value.isdecimal() and int(value) > 0:
        return int(value)
    return None


def parse_seconds(value: Any) -> float | None:
    if isinstance(value, bool) or value is None:
        return None
    try:
        number = float(value)
    except (TypeError, ValueError, OverflowError):
        return None
    return number if math.isfinite(number) and number >= 0 else None


def load_registry(registry_path: Path, project_root: Path) -> dict[str, Source]:
    """The developer must explicitly configure source-to-file mappings."""
    if not registry_path.is_file():
        return {}
    payload = json.loads(registry_path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict) or not isinstance(payload.get("sources"), list):
        raise ValueError("sources.json must contain a 'sources' array")
    registry: dict[str, Source] = {}
    aliases_seen: set[tuple[str, str]] = set()
    for item in payload["sources"]:
        source_id = str(item["id"]).strip()
        kind = str(item["type"]).strip()
        if not source_id or kind not in {"document", "video"} or source_id in registry:
            raise ValueError("Duplicate or invalid source id/type")
        candidate = Path(item["path"]).expanduser()
        if not candidate.is_absolute():
            candidate = project_root / candidate
        candidate = candidate.resolve()
        expected_suffixes = {"document": {".pdf"}, "video": {".mp4", ".webm", ".mov"}}
        if candidate.suffix.lower() not in expected_suffixes[kind]:
            raise ValueError(f"Unsupported media extension for {source_id}")
        aliases = tuple(str(a).strip() for a in item.get("aliases", []) if str(a).strip())
        for alias in aliases:
            alias_key = (kind, alias)
            if alias_key in aliases_seen:
                raise ValueError(f"Ambiguous source alias: {alias}")
            aliases_seen.add(alias_key)
        registry[source_id] = Source(source_id, kind, candidate, str(item.get("display_name") or source_id), aliases)
    return registry


def resolve_source(meta: Mapping[str, Any], kind: str, registry: Mapping[str, Source]) -> Source | None:
    expected = "video" if kind == "video" else "document"
    explicit_id = str(meta.get("source_id") or meta.get("video_id") or meta.get("document_id") or "").strip()
    if explicit_id:
        source = registry.get(explicit_id)
        return source if source and source.kind == expected else None
    legacy_alias = str(meta.get("source") or "").strip()
    # Deliberately no implicit filename matching or first-source fallback.
    matches = [s for s in registry.values() if s.kind == expected and legacy_alias in s.aliases]
    return matches[0] if len(matches) == 1 else None


def make_evidence(node: Any, index: int, registry: Mapping[str, Source]) -> Evidence:
    """Wrap a *retrieved node*, not a citation generated by an LLM."""
    original = getattr(node, "node", node)
    meta = dict(getattr(original, "metadata", {}) or {})
    kind = str(meta.get("type") or "text").lower()
    if kind not in {"text", "image", "video"}:
        kind = "text"
    source = resolve_source(meta, kind, registry)
    page = parse_page(meta.get("page_number"))
    seconds = parse_seconds(meta.get("seconds"))
    evidence_id = str(getattr(original, "node_id", None) or getattr(original, "id_", None) or f"retrieved-{index}")
    text = str(getattr(original, "text", "") or "")

    if source is None:
        status, reason = "unmapped", "No explicit source mapping matches this retrieved record."
    elif not source.path.is_file():
        status, reason = "missing", "Configured source file is not present on this computer."
    elif kind == "video" and seconds is None:
        status, reason = "invalid", "Video timestamp is missing or invalid."
    elif kind == "text" and page is None:
        status, reason = "invalid", "PDF page metadata is missing or invalid."
    elif kind == "image" and page is None:
        status, reason = "unavailable", "Image record lacks a trustworthy PDF page reference."
    else:
        status, reason = "ready", "Position supplied by retrieved source metadata."
    return Evidence(
        evidence_id=evidence_id, kind=kind, text=text, metadata=meta,
        page=page, seconds=seconds, source_id=source.source_id if source else None,
        source_name=source.display_name if source else str(meta.get("source") or "Unidentified source"),
        status=status, reason=reason,
    )


def label_for(e: Evidence | Mapping[str, Any]) -> str:
    kind = e.kind if isinstance(e, Evidence) else e.get("kind")
    page = e.page if isinstance(e, Evidence) else e.get("page")
    seconds = e.seconds if isinstance(e, Evidence) else e.get("seconds")
    if kind == "video":
        if seconds is None:
            return "Video · timestamp unavailable"
        total = int(seconds)
        return f"Video · {total // 60:02d}:{total % 60:02d}"
    if kind == "text":
        return f"Textbook · p.{page}" if page else "Textbook · page unavailable"
    return "Figure · source detail"
